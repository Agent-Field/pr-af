// Contract: _risk_signals ordering and triggers (auth/database areas, config
// suffixes, test paths; >=25 files trips the footprint signal).
func TestRiskSignalsGolden(t *testing.T) {
	pr := fixturePR()
	areas := extractAreas([]string{
		"src/auth/login.py", "db/migrations/0001_init.sql", "web/App.tsx",
		"cmd/main.go", "config/settings.yml", "tests/test_login.py",
		"Dockerfile", "README.md", "script.unknownext",
	})
	want := []string{
		"touches authentication or security-sensitive paths",
		"modifies data model or schema-affecting code",
		"includes configuration changes",
		"test behavior updated",
	}
	if got := riskSignals(pr, areas, len(pr.ChangedFiles)); !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v, want %v", got, want)
	}

	// 25 plain .go files: only the footprint signal (Python golden).
	files := make([]schemas.ChangedFile, 25)
	for i := range files {
		files[i] = schemas.ChangedFile{Path: "pkg/modx/filex.go"}
	}
	big := schemas.GitHubPRData{Title: "big", ChangedFiles: files}
	bigAreas := extractAreas([]string{"pkg/modx/filex.go"})
	want = []string{"large change footprint across many files"}
	if got := riskSignals(big, bigAreas, 25); !reflect.DeepEqual(got, want) {
		t.Fatalf("big: got %v, want %v", got, want)
	}
}

