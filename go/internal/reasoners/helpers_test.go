// Contract: _write_context_file creates <repo>/.pr-af-context/<name> with the
// exact content and returns its path.
func TestWriteContextFile(t *testing.T) {
	repo := t.TempDir()
	path, err := writeContextFile("hello context", "meta_semantic_context.json", repo)
	if err != nil {
		t.Fatal(err)
	}
	want := filepath.Join(repo, ".pr-af-context", "meta_semantic_context.json")
	if path != want {
		t.Fatalf("path = %q, want %q", path, want)
	}
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(b) != "hello context" {
		t.Fatalf("content = %q", b)
	}
}

